"""Chat sessions: a CRUD resource owned by the user in the Bearer token."""

import asyncio
from typing import Annotated
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Query, Response

from mnemonic.auth import get_current_user
from mnemonic.openapi import R401, R404
from mnemonic.schemas import (
    MessageOut,
    SessionCreate,
    SessionOut,
    SessionPage,
    SessionUpdate,
)
from mnemonic.store import Session, Store, User, get_store

# The router-level dependency runs before any handler, so no route here can forget the login.
router = APIRouter(
    prefix="/sessions",
    tags=["sessions"],
    dependencies=[Depends(get_current_user)],
    responses={401: R401},
)

CurrentUser = Annotated[User, Depends(get_current_user)]
StoreDep = Annotated[Store, Depends(get_store)]


def not_found() -> HTTPException:
    # The same answer for "no such id" and "someone else's id": ids must not be probeable.
    return HTTPException(status_code=404, detail="Session not found")


def session_out(s: Session) -> SessionOut:
    return SessionOut(id=s.id, title=s.title, created_at=s.created_at, updated_at=s.updated_at)


@router.post(
    "",
    status_code=201,
    response_model=SessionOut,
    summary="Create a session",
    description="Start an empty chat. The id is generated by the server. Without a title the "
    "session is called 'New chat' until the first question renames it.",
)
async def create_session(body: SessionCreate, user: CurrentUser, store: StoreDep) -> SessionOut:
    return session_out(await asyncio.to_thread(store.create_session, user.id, body.title))


@router.get(
    "",
    response_model=SessionPage,
    summary="List my sessions",
    description="Newest activity first. Offset pagination: `next` is the offset to request for "
    "the following page, or null on the last page.",
)
async def list_sessions(
    user: CurrentUser,
    store: StoreDep,
    limit: Annotated[int, Query(ge=1, le=100, description="Page size.")] = 20,
    offset: Annotated[int, Query(ge=0, description="How many sessions to skip.")] = 0,
) -> SessionPage:
    items, total = await asyncio.to_thread(store.list_sessions, user.id, limit, offset)
    following = offset + limit
    return SessionPage(
        items=[session_out(s) for s in items],
        total=total,
        limit=limit,
        offset=offset,
        next=following if following < total else None,
    )


@router.get(
    "/{session_id}",
    response_model=SessionOut,
    summary="Get a session",
    description="One of my sessions. Someone else's id answers 404, like a missing one.",
    responses={404: R404},
)
async def get_session(session_id: UUID, user: CurrentUser, store: StoreDep) -> SessionOut:
    found = await asyncio.to_thread(store.get_session, user.id, session_id)
    if found is None:
        raise not_found()
    return session_out(found)


@router.patch(
    "/{session_id}",
    response_model=SessionOut,
    summary="Rename a session",
    description="Change the title (1-100 characters, surrounding whitespace is trimmed).",
    responses={404: R404},
)
async def rename_session(
    session_id: UUID, body: SessionUpdate, user: CurrentUser, store: StoreDep
) -> SessionOut:
    found = await asyncio.to_thread(store.rename_session, user.id, session_id, body.title)
    if found is None:
        raise not_found()
    return session_out(found)


@router.delete(
    "/{session_id}",
    status_code=204,
    summary="Delete a session",
    description="Deletes the session with all its messages and LLM call logs.",
    responses={404: R404},
)
async def delete_session(session_id: UUID, user: CurrentUser, store: StoreDep) -> Response:
    if not await asyncio.to_thread(store.delete_session, user.id, session_id):
        raise not_found()
    return Response(status_code=204)


@router.get(
    "/{session_id}/messages",
    response_model=list[MessageOut],
    summary="Chat history",
    description="The messages of one of my sessions, oldest first.",
    responses={404: R404},
)
async def session_messages(session_id: UUID, user: CurrentUser, store: StoreDep) -> list[dict]:
    stored = await asyncio.to_thread(store.get_messages, user.id, session_id)
    if stored is None:
        raise not_found()
    return [
        {
            "id": m.id,
            "role": m.role,
            "content": m.content,
            "sources": m.sources,
            "created_at": m.created_at,
        }
        for m in stored
    ]
