from typing import Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field


class Message(BaseModel):
    """Internal message passed to LLM providers. Only the server creates `system` ones."""

    role: Literal["system", "user", "assistant"]
    content: str = Field(min_length=1)


class ClientMessage(BaseModel):
    """What the client may send: no `system` role, so it cannot touch the system prompt."""

    role: Literal["user", "assistant"]
    content: str = Field(min_length=1)


class ChatRequest(BaseModel):
    """One user turn. The client sends only its session id and the question: there is no
    field through which a `system` message (or a fake assistant turn) could get in."""

    model_config = ConfigDict(extra="forbid")  # an old-style `messages` list -> 422

    session_id: UUID  # generated by the client; knowing it is the only "key" to the history
    message: str = Field(min_length=1, max_length=2000)
